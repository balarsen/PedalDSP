#!/usr/bin/env python3
"""Export fitted KlonSim ODE model parameters as a C++ header for Daisy Seed.

Reads stage3_params.json, computes Direct-Form-II-Transposed biquad coefficients
at the Daisy target sample rate (default 48 kHz), and writes daisy/klonsim_params.h.
The biquad formulas match the Python training model exactly (Audio EQ Cookbook).

Usage:
    uv run python scripts/export_daisy_coeffs.py
    uv run python scripts/export_daisy_coeffs.py --sr 48000 --out daisy/klonsim_params.h
"""
from __future__ import annotations

import argparse
import json
import math
import shutil
from pathlib import Path

import scipy.signal


def _hpf_coeffs(fc: float, sr: int) -> tuple[list[float], list[float]]:
    """2nd-order Butterworth HPF coefficients.

    Matches SecondOrderHighpass._compute_hpf_biquad_coeffs() exactly.

    Args:
        fc: Cutoff frequency in Hz.
        sr: Sample rate in Hz.

    Returns:
        (b, a) where b=[b0,b1,b2] and a=[1,a1,a2].
    """
    b, a = scipy.signal.butter(2, fc / (sr / 2.0), btype="high")
    return list(map(float, b)), list(map(float, a))


def _shelf_coeffs(fc: float, gain_db: float, sr: int) -> tuple[list[float], list[float]]:
    """Audio EQ Cookbook high-shelf coefficients.

    Matches HighShelfBiquad._compute_coeffs() exactly (Q=0.707).

    Args:
        fc: Shelf frequency in Hz.
        gain_db: Gain in dB (positive = boost).
        sr: Sample rate in Hz.

    Returns:
        (b, a) where b=[b0,b1,b2] and a=[1,a1,a2].
    """
    A = 10.0 ** (gain_db / 40.0)
    sqrt_A = math.sqrt(A)
    w0 = 2.0 * math.pi * fc / sr
    cos_w0 = math.cos(w0)
    sin_w0 = math.sin(w0)
    alpha = sin_w0 / (2.0 * 0.707)

    b0 = A * ((A + 1) + (A - 1) * cos_w0 + 2.0 * sqrt_A * alpha)
    b1 = -2.0 * A * ((A - 1) + (A + 1) * cos_w0)
    b2 = A * ((A + 1) + (A - 1) * cos_w0 - 2.0 * sqrt_A * alpha)
    a0 = (A + 1) - (A - 1) * cos_w0 + 2.0 * sqrt_A * alpha
    a1 = 2.0 * ((A - 1) - (A + 1) * cos_w0)
    a2 = (A + 1) - (A - 1) * cos_w0 - 2.0 * sqrt_A * alpha

    return [b0 / a0, b1 / a0, b2 / a0], [1.0, a1 / a0, a2 / a0]


def _eval_h_db(b: list[float], a: list[float], f_hz: float, sr: int) -> float:
    """Evaluate |H(e^{jω})| in dB at a single frequency."""
    w = 2.0 * math.pi * f_hz / sr
    e1 = complex(math.cos(w), -math.sin(w))
    e2 = e1 * e1
    num = b[0] + b[1] * e1 + b[2] * e2
    den = a[0] + a[1] * e1 + a[2] * e2
    return 20.0 * math.log10(abs(num) / (abs(den) + 1e-30) + 1e-30)


def _write_header(
    path: Path,
    params: dict,
    hpf1_b: list[float],
    hpf1_a: list[float],
    hpf2_b: list[float],
    hpf2_a: list[float],
    shelf_b: list[float],
    shelf_a: list[float],
    sr: int,
) -> None:
    def _arr3(vals: list[float]) -> str:
        return "{{ {:+.9f}f, {:+.9f}f, {:+.9f}f }}".format(*vals)

    def _arr2(vals: list[float]) -> str:
        return "{{ {:+.9f}f, {:+.9f}f }}".format(*vals)

    lines = [
        "// Auto-generated by scripts/export_daisy_coeffs.py — do not edit manually.",
        f"// Source: stage3_params.json  |  Target SR: {sr} Hz",
        f"// Signal chain: HPF1({params['fc1_hz']:.1f} Hz) → ×drive → tanh",
        f"//               → HPF2({params['fc2_hz']:.1f} Hz) → Shelf({params['shelf_freq_hz']:.0f} Hz, {params['shelf_gain_db']:+.2f} dB) → ×level",
        "#pragma once",
        "",
        "namespace klonsim {",
        "",
        f"static constexpr float kDrive       = {params['drive']:.6f}f;",
        f"static constexpr float kOutputLevel = {params['output_level']:.6f}f;",
        "",
        f"// HPF1: 2nd-order Butterworth highpass at {params['fc1_hz']:.2f} Hz",
        "// Direct Form II Transposed — b=feedforward, a=feedback (a[0]=1 omitted)",
        f"static constexpr float kHpf1B[3] = {_arr3(hpf1_b)};",
        f"static constexpr float kHpf1A[2] = {_arr2(hpf1_a[1:])};",
        "",
        f"// HPF2: 2nd-order Butterworth highpass at {params['fc2_hz']:.2f} Hz",
        f"static constexpr float kHpf2B[3] = {_arr3(hpf2_b)};",
        f"static constexpr float kHpf2A[2] = {_arr2(hpf2_a[1:])};",
        "",
        f"// High shelf at {params['shelf_freq_hz']:.1f} Hz, {params['shelf_gain_db']:+.2f} dB (Q=0.707)",
        f"static constexpr float kShelfB[3] = {_arr3(shelf_b)};",
        f"static constexpr float kShelfA[2] = {_arr2(shelf_a[1:])};",
        "",
        "}  // namespace klonsim",
    ]
    path.write_text("\n".join(lines) + "\n")


def main() -> None:
    p = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    p.add_argument(
        "--params",
        type=Path,
        default=Path("results/pedalode/klonsim_v1/staged/stage3_params.json"),
        help="Path to stage3_params.json.",
    )
    p.add_argument(
        "--sr",
        type=int,
        default=48_000,
        help="Daisy target sample rate in Hz (default: 48000).",
    )
    p.add_argument(
        "--out-dir",
        type=Path,
        default=Path("results/pedalode/klonsim_v1/daisy"),
        help="Output directory for the generated header and firmware source files.",
    )
    args = p.parse_args()

    if not args.params.is_file():
        raise FileNotFoundError(f"Params not found: {args.params}")

    with open(args.params) as f:
        params = json.load(f)

    sr = args.sr
    hpf1_b, hpf1_a = _hpf_coeffs(params["fc1_hz"], sr)
    hpf2_b, hpf2_a = _hpf_coeffs(params["fc2_hz"], sr)
    shelf_b, shelf_a = _shelf_coeffs(params["shelf_freq_hz"], params["shelf_gain_db"], sr)

    args.out_dir.mkdir(parents=True, exist_ok=True)
    header_path = args.out_dir / "klonsim_params.h"
    _write_header(header_path, params, hpf1_b, hpf1_a, hpf2_b, hpf2_a, shelf_b, shelf_a, sr)
    print(f"[export] Written:  {header_path}")

    # Copy firmware source files so the output dir is a complete build directory
    firmware_src = Path("daisy")
    for fname in ("klonsim_pedal.cpp", "Makefile"):
        src = firmware_src / fname
        if src.is_file():
            shutil.copy2(str(src), str(args.out_dir / fname))
            print(f"[export] Copied:   {args.out_dir / fname}")

    print(f"[export] SR:       {sr} Hz")
    print(f"[export] drive:    {params['drive']:.4f}   output_level: {params['output_level']:.4f}")

    # Sanity-check frequency response table
    check_freqs = [20, 50, 80, 100, 200, 350, 500, 1000, 3000, 6000, 10000]
    check_freqs = [f for f in check_freqs if f < sr / 2]
    drive_db = 20.0 * math.log10(params["drive"] * params["output_level"] + 1e-30)

    print(f"\n{'Freq (Hz)':>10}  {'HPF1 (dB)':>10}  {'HPF2 (dB)':>10}  {'Shelf (dB)':>10}  {'Chain (dB)':>10}")
    print("-" * 58)
    for f in check_freqs:
        h1 = _eval_h_db(hpf1_b, hpf1_a, f, sr)
        h2 = _eval_h_db(hpf2_b, hpf2_a, f, sr)
        hs = _eval_h_db(shelf_b, shelf_a, f, sr)
        chain = drive_db + h1 + h2 + hs
        print(f"{f:>10}  {h1:>10.2f}  {h2:>10.2f}  {hs:>10.2f}  {chain:>10.2f}")
    print(f"\n  (chain = linear approx; tanh saturates above ~±0.3 input)")


if __name__ == "__main__":
    main()
